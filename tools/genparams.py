#!/usr/bin/env python3
"""Emit hash_params.inc -- per-build hash parameters for the dotlocal payload, same as the bellatrix one.

    genparams.py init --outdir DIR [--seed INT]

The API hash is Multiply-XOR (FNV-1a shape):

    h = SEED
    for each byte c:  h = (h ^ c) * PRIME      (mod 2**32)
    h ^= POST

PRIME is always odd: an odd multiplier is a bijection on Z/2**32 and diffuses
every input bit. An even one silently drops the top bit and collides.

Module names are folded with | 0x20 (the resolver reads the low byte of each
UTF-16 code unit); export names are matched case-sensitively. This mirrors
module_by_hash / export_by_hash in src/resolve.c.

Nothing about the hash is reused across builds: SEED, PRIME, POST and the
name hashes are all regenerated, so no constant survives as a signature.
"""
import argparse
import secrets
import sys

MASK = 0xFFFFFFFF

MODULE = "kernel32.dll"
EXPORTS = {
    "HASH_LOADLIBRARYA": "LoadLibraryA",
    "HASH_GETPROCADDRESS": "GetProcAddress",
    "HASH_MESSAGEBOXA": "MessageBoxA",
}
MODULE_DEFINE = "HASH_KERNEL32"
MODULES = {"HASH_USER32": "user32.dll", "HASH_NTDLL": "ntdll.dll"}


def mix(h, c, prime):
    return ((h ^ c) * prime) & MASK


def hash_module(name, seed, prime, post):
    h = seed
    for b in name.encode("ascii"):
        h = mix(h, b | 0x20, prime)
    return (h ^ post) & MASK


def hash_export(name, seed, prime, post):
    h = seed
    for b in name.encode("ascii"):
        h = mix(h, b, prime)
    return (h ^ post) & MASK


def cmd_init(args):
    if args.seed is not None:
        state = args.seed & MASK

        def rand32():
            nonlocal state
            state = (state * 0x01000193 + 0x811C9DC5) & MASK
            return state
    else:
        def rand32():
            return secrets.randbits(32)

    seed = rand32()
    post = rand32()
    while True:
        prime = rand32()
        if prime & 1:
            break

    lines = [
        "/* generated by tools/genparams.py -- do not edit */",
        "#define HASH_SEED   0x{:08X}".format(seed),
        "#define HASH_PRIME  0x{:08X}".format(prime),
        "#define HASH_POST   0x{:08X}".format(post),
        "",
        "#define {:<24} 0x{:08X}".format(
            MODULE_DEFINE, hash_module(MODULE, seed, prime, post)),
    ]
    for define, name in EXPORTS.items():
        lines.append("#define {:<24} 0x{:08X}".format(
            define, hash_export(name, seed, prime, post)))
    for define, name in MODULES.items():
        lines.append("#define {:<24} 0x{:08X}".format(
            define, hash_module(name, seed, prime, post)))
    lines.append("")

    with open(args.outdir + "/hash_params.h", "w") as f:
        f.write("\n".join(lines))

    sys.stderr.write(
        "genparams: seed=0x{:08X} prime=0x{:08X} post=0x{:08X}\n".format(
            seed, prime, post))


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("init", help="emit per-build hash parameters")
    p.add_argument("--outdir", required=True)
    p.add_argument("--seed", type=int, default=None,
                   help="deterministic mode: fixed integer seed")
    p.set_defaults(func=cmd_init)
    args = ap.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
