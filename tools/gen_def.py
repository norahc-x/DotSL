#!/usr/bin/env python3
"""Generate a .def mirroring the real module's export surface (names + ordinals).

    gen_def.py <real.dll> <library-name> > appraiser.def

The build gate diffs the generated surface against the real module, so this
is the single source of truth rather than a hand-maintained list.
"""
import re
import subprocess
import sys


def main():
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    real, lib = sys.argv[1], sys.argv[2]

    out = subprocess.run(["x86_64-w64-mingw32-objdump", "-p", real],
                         capture_output=True, text=True, check=True).stdout
    entries = []
    for line in out.splitlines():
        if line.rstrip().endswith("Export RVA"):   # EAT rows, not name rows
            continue
        m = re.search(r"\+base\[\s*(\d+)\]\s+\S+\s+([A-Za-z_][A-Za-z0-9_@$?]*)",
                      line)
        if m:
            entries.append((int(m.group(1)), m.group(2)))
    if not entries:
        print("no exports found", file=sys.stderr)
        return 1

    print(f"; generated by tools/gen_def.py from {lib}.dll -- do not edit")
    print(f"LIBRARY {lib}")
    print("EXPORTS")
    for ordinal, name in sorted(set(entries)):
        print(f"    {name} @{ordinal}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
